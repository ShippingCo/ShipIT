await test('OTP race has one winner, survives restart and revokes copied session immediately',{timeout:30000},async t=>{
  const db=await provisionDatabase(t); await db.prepareAuth();
  const pool=db.runtimePool({maxConnections:1}),auth=createAuthService(pool,keys),sent:Delivery[]=[];
  const worker=createDeliveryWorker(pool,keys,async message=>{sent.push(message);return {state:'accepted',reference:'synthetic'};});
  const user=await auth.provision('email','operator@example.test');
  const c=await auth.start('email','operator@example.test','browser-one','127.0.0.1');
  await worker.tick(); assert.equal(sent.length,1);
  await assert.rejects(auth.verify(c.challenge_id,sent[0]!.code,'foreign-browser','127.0.0.1'),denied);
  const race=await Promise.allSettled([auth.verify(c.challenge_id,sent[0]!.code,'browser-one','127.0.0.1'),auth.verify(c.challenge_id,sent[0]!.code,'browser-one','127.0.0.1')]);
  assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
  const winner=race.find(r=>r.status==='fulfilled'); assert.ok(winner?.status==='fulfilled' && !winner.value.linked);
  const token=winner.value.token;
  assert.equal((await auth.current(token)).user_id,user);
  const other=createAuthService(db.runtimePool(),keys);
  assert.equal((await other.current(token)).user_id,user);
  await auth.logout(token); await assert.rejects(other.current(token),denied);
  const stored=await db.adminQuery('SELECT * FROM shipit.auth_challenges');
  assert.equal(stored.rows[0]!.payload,null);
  assert.ok(!JSON.stringify(stored.rows).includes(sent[0]!.code));
  await assert.rejects(pool.query('DELETE FROM shipit.auth_security_events'));
  await worker.cleanup();
});
