await test('alternate-contact recovery requires recent session, rejects foreign IDs and revokes on unlink',{timeout:30000},async t=>{
  const db=await provisionDatabase(t);await db.prepareAuth();const pool=db.runtimePool({maxConnections:1}),auth=createAuthService(pool,keys),sent:Delivery[]=[];
  const worker=createDeliveryWorker(pool,keys,async m=>{sent.push(m);return {state:'accepted'};});
  const user=await auth.provision('email','alpha@example.test'); await auth.provision('email','beta@example.test');
  const c=await auth.start('email','alpha@example.test','b','ip');await worker.tick();
  const login=await auth.verify(c.challenge_id,sent[0]!.code,'b','ip');assert.ok(!login.linked);
  const link=await auth.start('whatsapp','+15555550101','b','ip',login.token);await worker.tick();
  await assert.rejects(auth.verify(link.challenge_id,sent[1]!.code,'b','ip','foreign'),denied);
  assert.deepEqual(await auth.verify(link.challenge_id,sent[1]!.code,'b','ip',login.token),{linked:true});
  const contacts=await auth.contacts(login.token);assert.equal(contacts.length,2);
  const foreign=(await db.adminQuery<{id:string}>('SELECT id FROM shipit.auth_identifiers WHERE user_id<>$1',[user])).rows[0]!.id;
  await assert.rejects(auth.unlink(login.token,foreign),e=>e instanceof HttpError && e.code==='ACTION_FORBIDDEN');
  await auth.unlink(login.token,contacts.find(c=>c.channel==='email')!.id);
  await assert.rejects(auth.current(login.token),denied);
});
await test('HTTP login rotates cookies, never returns credentials and database expiry denies access',{timeout:30000},async t=>{
  const db=await provisionDatabase(t);await db.prepareAuth();const pool=db.runtimePool(),auth=createAuthService(pool,keys),sent:Delivery[]=[];
  await auth.provision('email','http@example.test');
  const worker=createDeliveryWorker(pool,keys,async m=>{sent.push(m);return {state:'accepted'};});
  const logs:string[]=[];
  const config=parseEnvironment({NODE_ENV:'development',HOST:'127.0.0.1',PORT:'3000',LOG_LEVEL:'info',ALLOWED_ORIGINS:'http://localhost:5173',TRUSTED_PROXY_HOPS:'0',DATABASE_SECRET_REF:'local:database',DATABASE_TLS_MODE:'disable'});
  const app=buildServer({config,database:pool,auth:{keys,delivery:{},webhook:undefined},logSink:{write:s=>{logs.push(s);}}});
  t.after(()=>app.close());
  const boot=await app.inject('/auth/bootstrap');const browser=boot.cookies[0]!;
  const headers={origin:'http://localhost:5173','x-csrf-token':boot.json().csrf_token};
  const cookies:Record<string,string>={[browser.name]:browser.value};
  const start=await app.inject({method:'POST',url:'/auth/challenges',headers,cookies,payload:{channel:'email',address:'http@example.test'}});
  assert.equal(start.statusCode,200);await worker.tick();
  const login=await app.inject({method:'POST',url:'/auth/challenges/verify',headers,cookies,payload:{challenge_id:start.json().challenge_id,code:sent[0]!.code}});
  assert.equal(login.statusCode,200);assert.deepEqual(login.json(),{authenticated:true});
  const session=login.cookies.find(c=>c.name==='shipit_session')!;assert.ok(session.httpOnly);
  cookies[session.name]=session.value;
  assert.equal((await app.inject({url:'/auth/session',cookies})).statusCode,200);
  const next=await app.inject({method:'POST',url:'/auth/challenges',headers,cookies,payload:{channel:'email',address:'http@example.test'}});await worker.tick();
  const rotated=await app.inject({method:'POST',url:'/auth/challenges/verify',headers,cookies,payload:{challenge_id:next.json().challenge_id,code:sent[1]!.code}});
  assert.equal(rotated.statusCode,200);assert.notEqual(rotated.cookies[0]!.value,session.value);
  assert.equal((await app.inject({url:'/auth/session',cookies})).statusCode,401);
  const fresh=rotated.cookies[0]!.value;cookies[session.name]=fresh;
  await auth.logoutAll(fresh);assert.equal((await app.inject({url:'/auth/session',cookies})).statusCode,401);
  assert.ok(!logs.join('').includes(sent[0]!.code));assert.ok(!logs.join('').includes(session.value));assert.ok(!logs.join('').includes('http@example.test'));
});
await test('resend preserves code and expiry, stale delivery becomes uncertain and maintenance removes secrets',{timeout:30000},async t=>{
  const db=await provisionDatabase(t);await db.prepareAuth();const pool=db.runtimePool(),auth=createAuthService(pool,keys),sent:Delivery[]=[];
  const user=await auth.provision('email','expiry@example.test');
  const worker=createDeliveryWorker(pool,keys,async m=>{sent.push(m);return {state:'accepted'};});
  const c=await auth.start('email','expiry@example.test','b','ip');await worker.tick();
  await assert.rejects(auth.resend(c.challenge_id,'b','ip'),e=>e instanceof HttpError && e.code==='ACTION_FORBIDDEN');
  await db.adminQuery("UPDATE shipit.auth_challenges SET last_sent_at=clock_timestamp()-interval '61 seconds' WHERE id=$1",[c.challenge_id]);
  await auth.resend(c.challenge_id,'b','ip');await worker.tick();assert.equal(sent[0]!.code,sent[1]!.code);
  await db.adminQuery("UPDATE shipit.auth_challenges SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1",[c.challenge_id]);
  await assert.rejects(auth.verify(c.challenge_id,sent[0]!.code,'b','ip'),denied);await worker.cleanup();
  assert.equal((await db.adminQuery('SELECT payload FROM shipit.auth_challenges WHERE id=$1',[c.challenge_id])).rows[0]!.payload,null);
  await db.adminQuery("UPDATE shipit.auth_delivery_jobs SET state='sending',claimed_at=clock_timestamp()-interval '2 minutes' WHERE challenge_id=$1",[c.challenge_id]);
  assert.equal(await worker.tick(),false);
  assert.ok((await db.adminQuery('SELECT state FROM shipit.auth_delivery_jobs')).rows.every(r=>r.state==='uncertain'));
  const next=await auth.start('email','expiry@example.test','b','ip');await worker.tick();
  const login=await auth.verify(next.challenge_id,sent[2]!.code,'b','ip');assert.ok(!login.linked);
  await db.adminQuery("UPDATE shipit.auth_sessions SET idle_expires_at=clock_timestamp()-interval '1 second' WHERE user_id=$1",[user]);
  await assert.rejects(auth.current(login.token),denied);
});
