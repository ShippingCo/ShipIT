export type AdministrativeAction = typeof administrativeActions[number];
const ownerOnly: readonly string[] = ['settings.organization.read','settings.organization.update'];
export function canAdminister(roles: readonly OperatorRole[], action: string): boolean {
  if (!(administrativeActions as readonly string[]).includes(action)) return false;
  return roles.includes('org_admin') || !ownerOnly.includes(action) && roles.includes('franchise_admin');
}

